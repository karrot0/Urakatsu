"""Scene kernel: state, snapshot, edit, and document views.

The model is the same: a project owns ordered pages; every page is an entity tree;
entities carry typed components; relations connect entities; assets are
content-addressed blobs attached to an entity under a role.

Concurrency model (simplified from Koharu's patches): ``Snapshot`` is an immutable
view of one ``State``. ``Edit`` copies the pages it touches on first write, records
the base revision and the components it observed, and ``Session.commit`` rejects
the patch if any observed value changed since (the stale-patch rule). Each
commit pushes the previous page states on the undo stack.

Authorship follows ``Edit::prepare_value``: an edit made ``as`` a generation stamps
every value it writes as generated by that producer and refuses to overwrite or
remove user-owned values or values owned by another producer.
"""

from __future__ import annotations

