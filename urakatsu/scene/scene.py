class StalePatch(SceneError):
    pass


_ID_SOURCE: list[Optional[list[str]]] = [None]


def new_id() -> str:
    """Fresh id, or the next recorded id while an edit is being replayed onto a newer state."""
    queue = _ID_SOURCE[-1]
    if queue:
        return queue.pop(0)
    return uuid.uuid4().hex


def _logged(method):
    """Records top-level mutations (and the ids they minted) so a stale edit can be replayed."""

    def wrapper(self: "Edit", *args, **kwargs):
        if self._depth > 0:
            return method(self, *args, **kwargs)
        minted: list[str] = []
        self._depth += 1
        recorder = _Recorder(minted)
        try:
            with recorder:
                result = method(self, *args, **kwargs)
        finally:
            self._depth -= 1
        self._log.append((method.__name__, args, kwargs, minted))
        return result

    wrapper.__name__ = method.__name__
    wrapper.__doc__ = method.__doc__
    return wrapper


class _Recorder:
    """Captures ids minted by ``new_id`` during one logged call."""

    def __init__(self, minted: list[str]):
        self.minted = minted

    def __enter__(self):
        global new_id
        self._previous = new_id

        def recording() -> str:
            value = self._previous()
            self.minted.append(value)
            return value

        globals()["new_id"] = recording
        return self

    def __exit__(self, *exc):
        globals()["new_id"] = self._previous
        return False


