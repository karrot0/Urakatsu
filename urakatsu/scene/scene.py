@dataclass
class Relation:
    id: str
    kind: str
    source: str
    target: str
    origin: c.Origin = field(default_factory=c.UserOrigin)


@dataclass
class PageState:
    id: str
    entities: dict[str, Entity] = field(default_factory=dict)
    relations: dict[str, Relation] = field(default_factory=dict)


@dataclass
class State:
    revision: int = 0
    page_order: list[str] = field(default_factory=list)
    pages: dict[str, PageState] = field(default_factory=dict)
    project: dict[str, c.Component] = field(default_factory=dict)

    def page_for(self, entity: str) -> str:
        for page_id, page in self.pages.items():
            if entity in page.entities:
                return page_id
        raise SceneError(f"entity {entity} not found")

    def entity(self, entity: str) -> Entity:
        return self.pages[self.page_for(entity)].entities[entity]

    def contains(self, entity: str) -> bool:
        return any(entity in page.entities for page in self.pages.values())


# ---- positions -------------------------------------------------------------------------------------


class At:
    """Insertion position among siblings (``edit::At``)."""

    def __init__(self, kind: str, anchor: Optional[str] = None):
        self.kind = kind
        self.anchor = anchor

    START: "At"
    END: "At"

    @classmethod
    def before(cls, anchor: str) -> "At":
        return cls("before", anchor)

    @classmethod
    def after(cls, anchor: str) -> "At":
        return cls("after", anchor)

    def resolve(self, siblings: list[str]) -> int:
        if self.kind == "start":
            return 0
        if self.kind == "end":
            return len(siblings)
        if self.anchor not in siblings:
            raise SceneError(f"anchor {self.anchor} is not a sibling")
        index = siblings.index(self.anchor)
        return index if self.kind == "before" else index + 1


At.START = At("start")
At.END = At("end")


class RemovePolicy(Enum):
    REJECT_NON_EMPTY = "reject_non_empty"
    CASCADE = "cascade"
    PROMOTE_CHILDREN = "promote_children"


# ---- snapshot --------------------------------------------------------------------------------------


class Snapshot:
    def __init__(self, state: State, blobs: "BlobReader"):
        self._state = state
        self.blobs = blobs

    @property
    def revision(self) -> int:
        return self._state.revision

    @property
    def state(self) -> State:
        return self._state

    # structure
    def pages(self) -> list[str]:
        return list(self._state.page_order)

    def page(self, page_id: str) -> c.Page:
        if page_id not in self._state.pages:
            raise SceneError(f"page {page_id} not found")
        return self.component(page_id, c.Page)  # type: ignore[return-value]

    def contains(self, entity: str) -> bool:
        return self._state.contains(entity)

    def parent(self, entity: str) -> Optional[str]:
        return self._state.entity(entity).parent

    def children(self, entity: str) -> list[str]:
        return list(self._state.entity(entity).children)

    def subtree(self, root: str) -> Iterator[str]:
        """Pre-order traversal including ``root``."""
        stack = [root]
        while stack:
            current = stack.pop()
            yield current
            stack.extend(reversed(self._state.entity(current).children))

    def descendants(self, root: str) -> Iterator[str]:
        iterator = self.subtree(root)
        next(iterator)
        yield from iterator

    def page_of(self, entity: str) -> str:
        return self._state.page_for(entity)

    # components
    def component(self, entity: str, cls: type[C]) -> Optional[C]:
        value = self._state.entity(entity).components.get(cls.KIND)
        return value.model_copy(deep=True) if value is not None else None  # type: ignore[return-value]

    def has(self, entity: str, cls: type[c.Component]) -> bool:
        return cls.KIND in self._state.entity(entity).components

    def user_authored(self, entity: str) -> bool:
        """Whether the user set anything on ``entity`` or below it: a component, or an authored
        value inside one (a translation they typed)."""
        for each in (entity, *self.descendants(entity)):
            for value in self._state.entity(each).components.values():
                if c.is_user(getattr(value, "origin", None)):
                    return True
                if any(isinstance(field, c.Authored) and c.is_user(field.origin) for field in vars(value).values()):
                    return True
        return False

    def project_component(self, cls: type[C]) -> Optional[C]:
        value = self._state.project.get(cls.KIND)
        return value.model_copy(deep=True) if value is not None else None  # type: ignore[return-value]

    def entities_with(self, cls: type[c.Component]) -> list[str]:
        result = []
        for page_id in self._state.page_order:
            for entity_id in self.subtree(page_id):
                if self.has(entity_id, cls):
                    result.append(entity_id)
        return result

    # assets
    def asset(self, entity: str, role: str) -> Optional[c.Asset]:
        value = self._state.entity(entity).assets.get(role)
        return value.model_copy(deep=True) if value is not None else None

    def asset_bytes(self, entity: str, role: str) -> Optional[bytes]:
        asset = self.asset(entity, role)
        return self.blobs.read(asset.blob) if asset else None

    # relations
    def _page_relations(self, entity: str) -> dict[str, Relation]:
        return self._state.pages[self._state.page_for(entity)].relations

    def relation(self, relation_id: str) -> Relation:
        for page in self._state.pages.values():
            if relation_id in page.relations:
                return copy.copy(page.relations[relation_id])
        raise SceneError(f"relation {relation_id} not found")

    def relations_from(self, entity: str, kind: Optional[str] = None) -> list[Relation]:
        return [
            copy.copy(r)
            for r in self._page_relations(entity).values()
            if r.source == entity and (kind is None or r.kind == kind)
        ]

    def relations_to(self, entity: str, kind: Optional[str] = None) -> list[Relation]:
        return [
            copy.copy(r)
            for r in self._page_relations(entity).values()
            if r.target == entity and (kind is None or r.kind == kind)
        ]

    def relation_from(self, entity: str, kind: str) -> Optional[Relation]:
        found = self.relations_from(entity, kind)
        if len(found) > 1:
            raise SceneError(f"functional relation {kind} has several targets from {entity}")
        return found[0] if found else None

    # document views (document.rs)
    def text_group(self, page: str) -> Optional[str]:
        groups = [child for child in self.children(page) if self.has(child, c.TextGroup)]
        if len(groups) > 1:
            raise SceneError(f"page {page} contains multiple text groups")
        return groups[0] if groups else None

    def text_layers(self, page: str) -> list[str]:
        group = self.text_group(page)
        return self.children(group) if group else []

    def layer_content(self, layer: str) -> str:
        relation = self.relation_from(layer, c.Relations.PRESENTS)
        if relation is None:
            raise SceneError(f"text layer {layer} has no content")
        return relation.target

    def fit_target(self, layer: str) -> Optional[str]:
        relation = self.relation_from(layer, c.Relations.FITS_TO)
        return relation.target if relation else None

    def balloon_target(self, layer: str) -> Optional[str]:
        relation = self.relation_from(layer, c.Relations.FLOWS_IN)
        return relation.target if relation else None

    def automatic_target(self, layer: str) -> Optional[str]:
        return self.balloon_target(layer) or self.fit_target(layer)

    def frame(self, layer: str) -> Optional[c.Geometry]:
        """Authored presentation frame, or the current automatic placement target's geometry."""
        own = self.component(layer, c.Geometry)
        if own is not None:
            return own
        target = self.automatic_target(layer)
        return self.component(target, c.Geometry) if target else None

    def source_region(self, content: str) -> Optional[str]:
        relation = self.relation_from(content, c.Relations.RECOGNIZED_FROM)
        return relation.target if relation else None

    def region_kind(self, entity: str) -> Optional[str]:
        region = self.component(entity, c.Region)
        return region.kind if region else None

    def raster_layers(self, page: str, kind: Optional[c.RasterLayerKind] = None) -> list[str]:
        result = []
        for child in self.children(page):
            layer = self.component(child, c.RasterLayer)
            if layer is not None and (kind is None or layer.kind == kind):
                result.append(child)
        return result

    def edit(self) -> "Edit":
        return Edit(self, None)

    def edit_as(self, generation: c.Generation) -> "Edit":
        return Edit(self, generation)


class BlobReader:
    def read(self, blob: str) -> bytes:  # pragma: no cover - interface
        raise NotImplementedError

    def write(self, data: bytes) -> str:  # pragma: no cover - interface
        raise NotImplementedError


# ---- edit ------------------------------------------------------------------------------------------


@dataclass
class Patch:
    base_revision: int
    pages: dict[str, Optional[PageState]]  # page id -> new state (None = removed)
    page_order: Optional[list[str]]
    project: Optional[dict[str, c.Component]]
    observed: dict[tuple[str, str, str], object]  # (owner, kind, key) -> observed value
    pending_blobs: dict[str, bytes]
    generation: Optional[c.Generation]
    edit: Optional["Edit"] = None

    def is_empty(self) -> bool:
        return not self.pages and self.page_order is None and self.project is None


class Edit:
    def __init__(self, base: Snapshot, generation: Optional[c.Generation]):
        self.base = base
        self.generation = generation
        self._pages: dict[str, Optional[PageState]] = {}
        self._page_order: Optional[list[str]] = None
        self._project: Optional[dict[str, c.Component]] = None
        self._observed: dict[tuple[str, str, str], object] = {}
        self._blobs: dict[str, bytes] = {}
        self._log: list[tuple[str, tuple, dict, list[str]]] = []
        self._depth = 0

    def replay_onto(self, base: Snapshot) -> "Edit":
        """Re-applies this edit's operations, with the same ids, on top of ``base``."""
        replay = Edit(base, self.generation)
        replay._observed = dict(self._observed)
        replay._blobs = dict(self._blobs)
        for name, args, kwargs, minted in self._log:
            _ID_SOURCE.append(list(minted))
            try:
                getattr(replay, name)(*args, **kwargs)
            finally:
                _ID_SOURCE.pop()
        return replay

    # -- working copies --------------------------------------------------------------------------

    def _state_page(self, page: str) -> PageState:
        if page in self._pages:
            working = self._pages[page]
            if working is None:
                raise SceneError(f"page {page} was removed")
            return working
        if page not in self.base.state.pages:
            raise SceneError(f"page {page} not found")
        working = copy.deepcopy(self.base.state.pages[page])
        self._pages[page] = working
        return working

    def _read_page(self, page: str) -> PageState:
        if page in self._pages:
            working = self._pages[page]
            if working is None:
                raise SceneError(f"page {page} was removed")
            return working
        return self.base.state.pages[page]

    def _order(self) -> list[str]:
        if self._page_order is None:
            self._page_order = list(self.base.state.page_order)
        return self._page_order

    def page_for(self, entity: str) -> str:
        for page_id in self._order() if self._page_order is not None else self.base.state.page_order:
            try:
                state = self._read_page(page_id)
            except SceneError:
                continue
            if entity in state.entities:
                return page_id
        for page_id, state in self._pages.items():
            if state is not None and entity in state.entities:
                return page_id
        raise SceneError(f"entity {entity} not found")

    def _entity(self, entity: str, write: bool = False) -> Entity:
        page = self.page_for(entity)
        state = self._state_page(page) if write else self._read_page(page)
        return state.entities[entity]

    def snapshot(self) -> Snapshot:
        """A view of the base with this edit's changes applied (``Snapshot::preview``)."""
        state = State(
            revision=self.base.revision,
            page_order=list(self._page_order if self._page_order is not None else self.base.state.page_order),
            pages={**self.base.state.pages, **{k: v for k, v in self._pages.items() if v is not None}},
            project=dict(self._project if self._project is not None else self.base.state.project),
        )
        for page_id, value in self._pages.items():
            if value is None:
                state.pages.pop(page_id, None)
        return Snapshot(state, _OverlayBlobs(self.base.blobs, self._blobs))

    # -- observation (stale-patch detection) ------------------------------------------------------

    def observe(self, entity: str, cls: type[c.Component]) -> None:
        key = ("entity", entity, cls.KIND)
        if key not in self._observed:
            value = self.base.state.entity(entity).components.get(cls.KIND) if self.base.contains(entity) else None
            self._observed[key] = value.model_dump(mode="json") if value is not None else None

    def observe_assets(self, entity: str) -> None:
        key = ("assets", entity, "*")
        if key not in self._observed:
            assets = self.base.state.entity(entity).assets if self.base.contains(entity) else {}
            self._observed[key] = {role: asset.blob for role, asset in assets.items()}

    def observe_subtree(self, root: str) -> None:
        for entity in self.base.subtree(root):
            for kind in list(self.base.state.entity(entity).components):
                cls = c.COMPONENTS.get(kind)
                if cls is not None:
                    self.observe(entity, cls)

    # -- authorship ------------------------------------------------------------------------------

    def _lifecycle_origin(self) -> c.Origin:
        return c.generated(self.generation) if self.generation else c.user()

    def _check_removal(self, existing: Optional[c.Component]) -> None:
        if self.generation is None or existing is None:
            return
        origin = existing.get_origin()
        if origin is None:
            raise AuthorshipError(f"pipeline cannot remove unmanaged component {existing.KIND}")
        if isinstance(origin, c.UserOrigin):
            raise AuthorshipError("pipeline cannot overwrite or remove a user-owned component")
        if origin.generation.producer != self.generation.producer:
            raise AuthorshipError(
                f"producer {origin.generation.producer} owns this component, not {self.generation.producer}"
            )

    def _prepare(self, existing: Optional[c.Component], value: c.Component) -> c.Component:
        self._check_removal(existing)
        value = value.model_copy(deep=True)
        if self.generation is not None:
            if not value.set_origin(c.generated(self.generation)):
                raise AuthorshipError(f"pipeline cannot write unmanaged component {value.KIND}")
        elif value.get_origin() is not None:
            value.set_origin(c.user())
        return value

    # -- structure -------------------------------------------------------------------------------

    @_logged
    def add_page(self, page: c.Page, at: At = At.END) -> str:
        order = self._order()
        position = at.resolve(order)
        page_id = new_id()
        state = PageState(id=page_id)
        state.entities[page_id] = Entity(
            id=page_id,
            parent=None,
            components={
                c.Page.KIND: page.model_copy(),
                c.EntityOrigin.KIND: c.EntityOrigin(origin=self._lifecycle_origin()),
            },
        )
        self._pages[page_id] = state
        order.insert(position, page_id)
        return page_id

    @_logged
    def set_page_order(self, order: list[str]) -> None:
        """Reorders the project's pages; ``order`` must be a permutation of the current pages."""
        current = self._order()
        if len(order) != len(current) or set(order) != set(current):
            raise SceneError("page order must list every page exactly once")
        current[:] = order

    @_logged
    def set_page(self, page_id: str, page: c.Page) -> None:
        self._state_page(page_id).entities[page_id].components[c.Page.KIND] = page.model_copy()

    @_logged
    def add_entity(self, parent: str, at: At = At.END) -> str:
        page = self.page_for(parent)
        state = self._state_page(page)
        parent_entity = state.entities[parent]
        position = at.resolve(parent_entity.children)
        entity_id = new_id()
        state.entities[entity_id] = Entity(
            id=entity_id,
            parent=parent,
            components={c.EntityOrigin.KIND: c.EntityOrigin(origin=self._lifecycle_origin())},
        )
        parent_entity.children.insert(position, entity_id)
        return entity_id

    @_logged
    def move_entity(self, entity: str, parent: str, at: At = At.END) -> None:
        page = self.page_for(entity)
        if self.page_for(parent) != page:
            raise SceneError("entities cannot move between pages")
        state = self._state_page(page)
        current = state.entities[entity]
        if current.parent is None:
            raise SceneError("pages cannot be moved with move_entity")
        stack = [entity]
        while stack:  # Error::HierarchyCycle: the new parent may not be the entity or its descendant
            node = stack.pop()
            if node == parent:
                raise SceneError("hierarchy cycle: cannot move an entity under itself")
            stack.extend(state.entities[node].children)
        state.entities[current.parent].children.remove(entity)
        siblings = state.entities[parent].children
        siblings.insert(at.resolve(siblings), entity)
        current.parent = parent

    def _check_lifecycle_removal(self, entity: Entity) -> None:
        if self.generation is None:
            return
        lifecycle = entity.components.get(c.EntityOrigin.KIND)
        origin = lifecycle.origin if lifecycle is not None else None  # type: ignore[attr-defined]
        if not isinstance(origin, c.GeneratedOrigin) or origin.generation.producer != self.generation.producer:
            raise AuthorshipError("pipeline can only remove entities it created")

    @_logged
    def remove_entity(self, entity: str, policy: RemovePolicy = RemovePolicy.REJECT_NON_EMPTY) -> None:
        page = self.page_for(entity)
        state = self._state_page(page)
        target = state.entities[entity]
        if entity != page and c.TextGroup.KIND in target.components:
            raise SceneError("the page text group cannot be removed")
        subtree = []
        stack = [entity]
        while stack:
            current = stack.pop()
            subtree.append(current)
            stack.extend(state.entities[current].children)
        for entity_id in subtree:
            self._check_lifecycle_removal(state.entities[entity_id])
        if policy is RemovePolicy.REJECT_NON_EMPTY and target.children:
            raise SceneError(f"entity {entity} is not empty")
        if policy is RemovePolicy.PROMOTE_CHILDREN and entity == page and target.children:
            raise SceneError("page children cannot be promoted")
        incident = [r for r in state.relations.values() if r.source in subtree or r.target in subtree]
        if policy is not RemovePolicy.CASCADE and incident:
            raise SceneError(f"entity {entity} has incident relations")
        for relation in incident:
            del state.relations[relation.id]
        if entity == page:
            self._pages[page] = None
            self._order().remove(page)
            return
        parent = state.entities[target.parent]  # type: ignore[index]
        index = parent.children.index(entity)
        parent.children.remove(entity)
        if policy is RemovePolicy.PROMOTE_CHILDREN:
            for offset, child in enumerate(target.children):
                state.entities[child].parent = target.parent
                parent.children.insert(index + offset, child)
            subtree = [entity]
        for entity_id in subtree:
            del state.entities[entity_id]

    # -- components ------------------------------------------------------------------------------

    @_logged
    def set(self, entity: str, value: c.Component) -> None:
        if value.STRUCTURAL:
            raise SceneError("structural components use dedicated scene methods")
        self.observe(entity, type(value)) if self.base.contains(entity) else None
        target = self._entity(entity, write=True)
        target.components[value.KIND] = self._prepare(target.components.get(value.KIND), value)

    @_logged
    def remove(self, entity: str, cls: type[c.Component]) -> None:
        if cls.STRUCTURAL:
            raise SceneError("structural components use dedicated scene methods")
        target = self._entity(entity, write=True)
        existing = target.components.get(cls.KIND)
        self._check_removal(existing)
        target.components.pop(cls.KIND, None)

    @_logged
    def set_project(self, value: c.Component) -> None:
        if self._project is None:
            self._project = dict(self.base.state.project)
        self._project[value.KIND] = self._prepare(self._project.get(value.KIND), value)

    def component(self, entity: str, cls: type[C]) -> Optional[C]:
        value = self._entity(entity).components.get(cls.KIND)
        return value.model_copy(deep=True) if value is not None else None  # type: ignore[return-value]

    # -- assets ----------------------------------------------------------------------------------

    @_logged
    def set_asset(self, entity: str, role: str, value: c.AssetInput) -> None:
        target = self._entity(entity, write=True)
        existing = target.assets.get(role)
        if existing is not None and self.generation is not None:
            if isinstance(existing.origin, c.UserOrigin):
                raise AuthorshipError("pipeline cannot overwrite a user-owned asset")
        blob = self.base.blobs.address(value.data) if hasattr(self.base.blobs, "address") else new_id()
        self._blobs[blob] = value.data
        target.assets[role] = c.Asset(
            origin=self._lifecycle_origin(), blob=blob, media_type=value.media_type, metadata=value.metadata
        )

    @_logged
    def remove_asset(self, entity: str, role: str) -> None:
        target = self._entity(entity, write=True)
        existing = target.assets.get(role)
        if existing is not None and self.generation is not None and isinstance(existing.origin, c.UserOrigin):
            raise AuthorshipError("pipeline cannot remove a user-owned asset")
        target.assets.pop(role, None)

    # -- relations -------------------------------------------------------------------------------

    @_logged
    def add_relation(self, kind: str, source: str, target: str) -> str:
        page = self.page_for(source)
        if self.page_for(target) != page:
            raise SceneError("relations cannot cross pages")
        state = self._state_page(page)
        if kind in c.Relations.FUNCTIONAL:
            for existing in state.relations.values():
                if existing.kind == kind and existing.source == source:
                    raise SceneError(f"{source} already has a {kind} relation")
        relation_id = new_id()
        state.relations[relation_id] = Relation(
            id=relation_id, kind=kind, source=source, target=target, origin=self._lifecycle_origin()
        )
        return relation_id

    def relate(self, kind: str, source: str, target: str) -> str:
        return self.add_relation(kind, source, target)

    @_logged
    def remove_relation(self, relation_id: str) -> None:
        for page_id in list(self._order() if self._page_order is not None else self.base.state.page_order):
            state = self._read_page(page_id)
            if relation_id in state.relations:
                existing = state.relations[relation_id]
                if self.generation is not None and isinstance(existing.origin, c.UserOrigin):
                    raise AuthorshipError("pipeline cannot remove a user-owned relation")
                del self._state_page(page_id).relations[relation_id]
                return
        raise SceneError(f"relation {relation_id} not found")

    def relations_from(self, entity: str, kind: Optional[str] = None) -> list[Relation]:
        state = self._read_page(self.page_for(entity))
        return [copy.copy(r) for r in state.relations.values() if r.source == entity and (kind is None or r.kind == kind)]

    def relations_to(self, entity: str, kind: Optional[str] = None) -> list[Relation]:
        state = self._read_page(self.page_for(entity))
        return [copy.copy(r) for r in state.relations.values() if r.target == entity and (kind is None or r.kind == kind)]

    # -- document intents (document.rs) -----------------------------------------------------------

    @_logged
    def ensure_text_group(self, page: str) -> str:
        state = self._read_page(page)
        groups = [child for child in state.entities[page].children if c.TextGroup.KIND in state.entities[child].components]
        if len(groups) > 1:
            raise SceneError("page contains multiple text groups")
        if groups:
            group = groups[0]
            if self.generation is None:
                lifecycle = self._entity(group, write=True)
                lifecycle.components[c.EntityOrigin.KIND] = c.EntityOrigin(origin=c.user())
            return group
        group = self.add_entity(page, At.END)
        self.set(group, c.Group(origin=self._lifecycle_origin(), name="Text"))
        self.set(group, c.Visibility(origin=self._lifecycle_origin(), visible=True, opacity=1.0))
        self._entity(group, write=True).components[c.TextGroup.KIND] = c.TextGroup()
        return group

    @_logged
    def add_text_content(self, parent: str, at: At = At.END) -> str:
        entity = self.add_entity(parent, at)
        self.set(entity, c.TextContent())
        return entity

    @_logged
    def add_text_layer(self, page: str, at: At, content: str, layout: c.TextLayout) -> str:
        group = self.ensure_text_group(page)
        layer = self.add_entity(group, at)
        self.set(layer, layout)
        self.relate(c.Relations.PRESENTS, layer, content)
        return layer

    @_logged
    def add_analysis_region(self, parent: str, at: At, kind: str, geometry: c.Geometry, label: Optional[str] = None) -> str:
        entity = self.add_entity(parent, at)
        self.set(entity, geometry)
        self.set(entity, c.Region(kind=kind, label=label))
        return entity

    # -- finish ----------------------------------------------------------------------------------

    def finish(self) -> Patch:
        return Patch(
            base_revision=self.base.revision,
            pages=dict(self._pages),
            page_order=list(self._page_order) if self._page_order is not None else None,
            project=dict(self._project) if self._project is not None else None,
            observed=dict(self._observed),
            pending_blobs=dict(self._blobs),
            generation=self.generation,
            edit=self,
        )


class _OverlayBlobs(BlobReader):
    def __init__(self, base: BlobReader, pending: dict[str, bytes]):
        self.base = base
        self.pending = pending

    def read(self, blob: str) -> bytes:
        if blob in self.pending:
            return self.pending[blob]
        return self.base.read(blob)

    def address(self, data: bytes) -> str:
        return self.base.address(data)  # type: ignore[attr-defined]
