"""Local GGUF translation model catalog.

Generated by a one-off port script from the commit-pinned upstream catalog: the ids,
quantizations (Hugging Face filenames), generation defaults, pinned revisions, vision
projectors and supported target languages are copied verbatim. Do not hand-edit;
re-run the port against the Rust source instead.
"""

from __future__ import annotations

from dataclasses import dataclass

from urakatsu.providers.translation.language import Language

DEFAULT_MODEL = "gemma4-12b-it"
DEFAULT_QUANTIZATION = "Q4_K_XL"


@dataclass(frozen=True)
class QuantizationDefinition:
    id: str
    name: str
    filename: str


@dataclass(frozen=True)
class ModelGeneration:
    """``ModelGeneration``: per-model sampling defaults; ``None`` means unset."""

    temperature: float | None = None
    top_k: int | None = None
    top_p: float | None = None
    min_p: float | None = None
    max_tokens: int | None = None
    repeat_penalty: float | None = None
    frequency_penalty: float | None = None
    presence_penalty: float | None = None


@dataclass(frozen=True)
class LocalModelDescriptor:
    id: str
    name: str
    reasoning: bool
    quantizations: tuple[QuantizationDefinition, ...]
    generation: ModelGeneration
    repository: str
    revision: str
    projector: str | None
    # None means every language.
    target_languages: frozenset[Language] | None

    def supports_language(self, language: Language) -> bool:
        return self.target_languages is None or language in self.target_languages

    def quantization(self, quantization_id: str | None) -> QuantizationDefinition:
        """``LocalModelDescriptor::filename``: the named quantization, else the first one."""
        wanted = quantization_id or (self.quantizations[0].id if self.quantizations else None)
        if wanted is None:
            raise ValueError(f"local model '{self.id}' has no quantizations")
        for definition in self.quantizations:
            if definition.id == wanted:
                return definition
        raise ValueError(f"unknown quantization '{wanted}' for '{self.id}'")

